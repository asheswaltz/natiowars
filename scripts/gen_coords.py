import math

# Canvas transformations
# Southern Europe: crop canvas [0-700] x [150-616], scale = 900/700
S_SCALE = 900 / 700  # 1.28571...
S_Y_OFF = 150

# Scandinavia: crop canvas [0-600] x [0-400], scale = 900/600
N_SCALE = 900 / 600  # 1.5


def tr_s(pts):
    """Transform point list for Southern Europe."""
    return [[round(x * S_SCALE), round((y - S_Y_OFF) * S_SCALE)] for x, y in pts]

def tc_s(x, y):
    """Transform center for Southern Europe."""
    return round(x * S_SCALE), round((y - S_Y_OFF) * S_SCALE)

def ds_s(d):
    return round(d * S_SCALE)

def tr_n(pts):
    """Transform point list for Scandinavia."""
    return [[round(x * N_SCALE), round(y * N_SCALE)] for x, y in pts]

def tc_n(x, y):
    return round(x * N_SCALE), round(y * N_SCALE)

def ds_n(d):
    return round(d * N_SCALE)

def fmt_path(pts):
    lines = []
    for i in range(0, len(pts), 5):
        chunk = pts[i:i+5]
        lines.append('          ' + ', '.join(f'[{p[0]},{p[1]}]' for p in chunk))
    return ',\n'.join(lines)

