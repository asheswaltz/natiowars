// ── Language detection ──
// Priority: ?lang=xx URL param > navigator.language > 'fr'
function detectLanguage() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  if (urlLang) {
    const short = urlLang.split('-')[0].toLowerCase();
    if (I18N[short]) return short;
  }
  const navLang = (navigator.language || navigator.userLanguage || 'fr').split('-')[0].toLowerCase();
  if (I18N[navLang]) return navLang;
  return 'fr';
}

const LANG = detectLanguage();
const STRINGS = I18N[LANG] || I18N['fr'];

function T(key, vars) {
  let str = STRINGS[key];
  if (str === undefined) {
    str = I18N['fr'][key];
  }
  if (str === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split('{' + k + '}').join(v);
    }
  }
  return str;
}

function TLevel(levelNum) {
  return T('levelTitle_' + levelNum) || ('Level ' + levelNum);
}

function TCountry(countryId) {
  return T('country_' + countryId) || countryId;
}

function TPlural(count) {
  if (LANG === 'de') return count > 1 ? 'e' : '';
  return count > 1 ? 's' : '';
}

function isTouchDevice() {
  return 'ontouchstart' in window || navigator.maxTouchPoints > 0;
}
